"""Restricted provider bodies (LayerZero Scan, 1Click, TronScan) are kept out of git; replay explains their absence."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import httpx
import pytest

from ledgerhunt import stage2
from ledgerhunt.core import restricted
from ledgerhunt.core.http import RecordingClient, ReplayMiss, RestrictedBodyMissing


def _store(tmp_path: Path) -> Path:
    """A store with one LayerZero Scan, one 1Click and one TronGrid response."""

    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, json={"host": request.url.host, "path": request.url.path})

    store = tmp_path / "store"
    http = RecordingClient(mode="record", store_dir=store, shared_limiter=False, transport=httpx.MockTransport(handler))
    http.get("https://scan.layerzero-api.com/v1/messages/tx/0xab", provider="layerzero_scan")
    http.get("https://1click.chaindefuser.com/v0/status", params={"depositAddress": "0x1"}, provider="near_intents_1click")
    http.get("https://api.trongrid.io/wallet/getnowblock", provider="trongrid")
    http.close()
    return store


def _body_path(store: Path, provider: str) -> Path:
    for line in (store / "index.jsonl").read_text(encoding="utf-8").splitlines():
        row = json.loads(line)
        if row["provider"] == provider:
            return store / "objects" / row["body_sha256"][:2] / row["body_sha256"]
    raise AssertionError(provider)


def test_provider_classification():
    assert restricted.is_restricted("layerzero_scan")
    assert restricted.is_restricted("near_intents_1click_keyed")
    assert restricted.is_restricted("tronscan_pending_consent")
    assert not restricted.is_restricted("trongrid") and not restricted.is_restricted(None)
    assert restricted.absent_message(["layerzero_scan", "near_intents_1click"]) == \
        "ответ LayerZero Scan / 1Click не хранится в git по условиям провайдера"


def test_generated_gitignore_lists_only_restricted_bodies(tmp_path):
    store = _store(tmp_path)
    text = restricted.gitignore_text(store)
    lz, oneclick, tg = (_body_path(store, p) for p in ("layerzero_scan", "near_intents_1click", "trongrid"))
    rel = lambda p: "/" + p.relative_to(store).as_posix()  # noqa: E731
    assert rel(lz) in text and rel(oneclick) in text and rel(tg) not in text
    assert text.startswith("# GENERATED by `python -m ledgerhunt.core.restricted`")


def test_replay_explains_absent_restricted_body(tmp_path):
    store = _store(tmp_path)
    _body_path(store, "layerzero_scan").unlink()
    _body_path(store, "near_intents_1click").unlink()
    st = restricted.store_status(store)
    assert st.all_absent and st.listed == 2 and st.present == 0
    assert "LayerZero Scan" in restricted.absent_reason([str(store)])
    http = RecordingClient(mode="replay", store_dir=store, shared_limiter=False)
    assert http.get("https://api.trongrid.io/wallet/getnowblock", provider="trongrid").ok  # unrestricted: unchanged
    with pytest.raises(RestrictedBodyMissing) as exc:
        http.get("https://scan.layerzero-api.com/v1/messages/tx/0xab", provider="layerzero_scan")
    assert isinstance(exc.value, ReplayMiss)
    assert "ответ LayerZero Scan не хранится в git по условиям провайдера" in str(exc.value)


def test_partly_missing_bodies_are_not_a_fresh_clone(tmp_path):
    store = _store(tmp_path)
    _body_path(store, "layerzero_scan").unlink()
    st = restricted.store_status(store)
    assert st.partial and not st.all_absent
    assert restricted.absent_reason([str(store)]) is None  # the area runs and fails on the missing body


def test_stage2_skips_area_when_restricted_bodies_absent(tmp_path, monkeypatch, capsys):
    import sys
    import types

    store = _store(tmp_path)
    calls = []
    mod = types.ModuleType("_ledgerhunt_test_restricted_area")
    mod.run = lambda args: calls.append(args) or 0
    monkeypatch.setitem(sys.modules, mod.__name__, mod)
    cmd = stage2.Stage2Command("unit", mod.__name__, "unit", restricted_stores=(str(store),))
    args = argparse.Namespace(http_mode="replay", llm=False)
    assert stage2.run_commands([cmd], args) == 0 and len(calls) == 1  # bodies present: the area runs
    _body_path(store, "layerzero_scan").unlink()
    _body_path(store, "near_intents_1click").unlink()
    assert stage2.run_commands([cmd], args) == 0 and len(calls) == 1  # fresh clone: skipped with a message
    out = capsys.readouterr().out
    assert "пропущено" in out and "не хранится в git по условиям провайдера" in out


def test_committed_stores_keep_restricted_bodies_out_of_git():
    """Every restricted body present on disk is listed in its store's generated .gitignore.

    Fails after a live run that recorded new LayerZero Scan / 1Click / TronScan responses:
    run ``python -m ledgerhunt.core.restricted`` and commit the updated lists.
    """
    stale = restricted.stale_gitignores()
    assert not stale, f"out of date: {stale}; run: python -m ledgerhunt.core.restricted"
    for st in restricted.STORES:
        root = restricted._store_path(st)
        if not (root / "index.jsonl").is_file():
            continue
        for sha in restricted.restricted_bodies(root):
            p = root / "objects" / sha[:2] / sha
            if p.is_file():
                assert hashlib.sha256(p.read_bytes()).hexdigest() == sha
