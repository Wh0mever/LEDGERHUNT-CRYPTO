"""Raw responses of providers whose terms do not allow storing them in git.

Until the owners get permission, the response *bodies* of these providers stay on the machine
that recorded them and are kept out of git:

- LayerZero Scan (provider ``layerzero_scan``): terms allow personal non-commercial use only
  and do not allow storing or copying the data;
- NEAR Intents 1Click (``near_intents_1click``, ``near_intents_1click_keyed``): data may not be
  stored for more than 24 hours;
- TronScan (``tronscan*``): written consent for commercial use of the API is pending.

How: every store in ``STORES`` gets a generated ``.gitignore`` that lists the body files
(``objects/<2>/<sha256>``) of index rows from these providers. The index rows themselves
(request key, status, size, latency, a few response headers; no body) stay committed.
A body shared with an unrestricted provider (identical bytes) is not listed.

Effect: replay on the recording machine is unchanged (the files stay on disk). In a fresh
clone the bodies are absent: ``stage2 --replay`` skips the areas that need them with
``ABSENT_MESSAGE`` and pytest skips the tests that need them.

Regenerate after every live (record/cache) run, because new responses are appended::

    python -m ledgerhunt.core.restricted          # rewrite the generated .gitignore files
    python -m ledgerhunt.core.restricted --check  # exit 1 when a list is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path

from .paths import repo_root

# provider name prefix (as written in index.jsonl) -> human label
PROVIDER_PREFIXES: dict[str, str] = {
    "layerzero_scan": "LayerZero Scan",
    "near_intents_1click": "1Click",
    "tronscan": "TronScan",
}

# stores (repo-relative) that hold responses of these providers
STORES: tuple[str, ...] = (
    "data/http-store",
    "tests/fixtures/case-001/raw/http-store",
    "tests/fixtures/case-001/raw/tronscan-pending-consent",
)

ABSENT_MESSAGE = "ответ {labels} не хранится в git по условиям провайдера"

_HEADER = """\
# GENERATED by `python -m ledgerhunt.core.restricted` -- do not edit by hand.
#
# Response bodies of providers whose terms do not allow storing them in git
# (until the owners get permission):
#   - LayerZero Scan: personal non-commercial use only, no storing or copying;
#   - NEAR Intents 1Click: no storing beyond 24 hours;
#   - TronScan: written consent for commercial API use is pending.
# The bodies stay on the machine that recorded them, so replay there is unchanged.
# Index rows (index.jsonl: request, status, size, a few headers; no body) stay committed.
# In a fresh clone the bodies are absent: `stage2 --replay` skips the areas that need
# them and pytest skips the tests that need them.
#
# Regenerate after every live run:  python -m ledgerhunt.core.restricted
# Check (also done by pytest):      python -m ledgerhunt.core.restricted --check
"""


def label_of(provider: str | None) -> str | None:
    """Human label when ``provider`` is restricted, else None."""
    p = (provider or "").lower()
    for prefix, label in PROVIDER_PREFIXES.items():
        if p.startswith(prefix):
            return label
    return None


def is_restricted(provider: str | None) -> bool:
    return label_of(provider) is not None


def absent_message(providers: set[str] | list[str] | tuple[str, ...]) -> str:
    found = {label_of(p) or p for p in providers}
    labels = [lab for lab in PROVIDER_PREFIXES.values() if lab in found] + sorted(found - set(PROVIDER_PREFIXES.values()))
    return ABSENT_MESSAGE.format(labels=" / ".join(labels) if labels else "провайдера")


def _store_path(store: Path | str) -> Path:
    p = Path(store)
    return p if p.is_absolute() else repo_root() / p


def _index_rows(store: Path) -> list[dict]:
    idx = store / "index.jsonl"
    if not idx.is_file():
        return []
    rows = []
    with open(idx, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                try:
                    rows.append(json.loads(line))
                except ValueError:
                    continue
    return rows


def restricted_bodies(store: Path | str) -> dict[str, set[str]]:
    """sha256 of every restricted body in ``store`` -> providers that returned it."""
    root = _store_path(store)
    restricted: dict[str, set[str]] = {}
    shared: set[str] = set()
    for r in _index_rows(root):
        sha = r.get("body_sha256")
        if not sha:
            continue
        if is_restricted(r.get("provider")):
            restricted.setdefault(sha, set()).add(r.get("provider") or "")
        else:
            shared.add(sha)
    return {sha: provs for sha, provs in restricted.items() if sha not in shared}


@dataclass(frozen=True)
class StoreStatus:
    store: str
    listed: int  # restricted bodies referenced by the index
    present: int  # of them, present on disk
    providers: frozenset[str]  # restricted providers whose bodies are missing

    @property
    def all_absent(self) -> bool:
        """Fresh-clone state: the index references restricted bodies and none is on disk."""
        return self.listed > 0 and self.present == 0

    @property
    def partial(self) -> bool:
        return 0 < self.present < self.listed


def store_status(store: Path | str) -> StoreStatus:
    root = _store_path(store)
    bodies = restricted_bodies(root)
    present = 0
    missing_providers: set[str] = set()
    for sha, provs in bodies.items():
        if (root / "objects" / sha[:2] / sha).is_file():
            present += 1
        else:
            missing_providers |= provs
    rel = root.relative_to(repo_root()).as_posix() if root.is_relative_to(repo_root()) else root.as_posix()
    return StoreStatus(rel, len(bodies), present, frozenset(missing_providers))


def absent_reason(stores: tuple[str, ...] | list[str]) -> str | None:
    """Message when the restricted bodies of any of ``stores`` are all absent (fresh clone), else None.

    A partly missing set is NOT a fresh clone: the replay then fails on the first missing body
    (never a silent skip on the machine that holds the data).
    """
    hit = [s for s in (store_status(st) for st in stores) if s.all_absent]
    if not hit:
        return None
    providers = set().union(*(s.providers for s in hit))
    where = ", ".join(s.store for s in hit)
    return f"{absent_message(providers)} (тел ответов нет в {where}; полный повтор — на машине владельцев)"


def gitignore_text(store: Path | str) -> str:
    bodies = restricted_bodies(store)
    by_provider: dict[str, list[str]] = {}
    for sha, provs in bodies.items():
        by_provider.setdefault(" + ".join(sorted(provs)), []).append(sha)
    lines = [_HEADER]
    for provs in sorted(by_provider):
        shas = sorted(by_provider[provs])
        lines.append(f"# {provs}: {len(shas)} bodies")
        lines.extend(f"/objects/{sha[:2]}/{sha}" for sha in shas)
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def write_gitignores(stores: tuple[str, ...] = STORES) -> list[tuple[str, int, bool]]:
    """(store, bodies listed, changed) per store; stores without an index are skipped."""
    out = []
    for st in stores:
        root = _store_path(st)
        if not (root / "index.jsonl").is_file():
            continue
        text = gitignore_text(root)
        p = root / ".gitignore"
        old = p.read_text(encoding="utf-8") if p.is_file() else None
        if old != text:
            p.write_text(text, encoding="utf-8", newline="\n")
        out.append((st, len(restricted_bodies(root)), old != text))
    return out


def stale_gitignores(stores: tuple[str, ...] = STORES) -> list[str]:
    """Stores whose generated .gitignore misses a restricted body that is present on disk."""
    stale = []
    for st in stores:
        root = _store_path(st)
        if not (root / "index.jsonl").is_file():
            continue
        p = root / ".gitignore"
        listed = set(p.read_text(encoding="utf-8").splitlines()) if p.is_file() else set()
        for sha in restricted_bodies(root):
            if (root / "objects" / sha[:2] / sha).is_file() and f"/objects/{sha[:2]}/{sha}" not in listed:
                stale.append(st)
                break
    return stale


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m ledgerhunt.core.restricted",
                                 description="Keep restricted provider response bodies out of git.")
    ap.add_argument("--check", action="store_true", help="exit 1 when a generated .gitignore is out of date")
    args = ap.parse_args(argv)
    if args.check:
        stale = stale_gitignores()
        for st in stale:
            print(f"out of date: {st}/.gitignore -- run: python -m ledgerhunt.core.restricted")
        return 1 if stale else 0
    for st, n, changed in write_gitignores():
        print(f"{st}/.gitignore: {n} restricted bodies listed{' (updated)' if changed else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
